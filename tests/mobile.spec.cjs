const { test, expect, devices } = require('@playwright/test');
const { spawn } = require('node:child_process');
const { once } = require('node:events');
test.use({ ...devices['iPhone 13'], browserName:'chromium' });
test.beforeEach(async ({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/');
 await expect(page.locator('#libraryStatus')).toContainText('105 exercices',{timeout:15000});
 await page.evaluate(()=>localStorage.clear());
 await page.reload();
 await expect(page.locator('#libraryStatus')).toContainText('105 exercices',{timeout:15000});
 page.__errors=errors;
});
test('bibliothèque, favoris, recherche et échappement',async ({page})=>{
 await page.getByRole('button',{name:'Jeux'}).click();
 await expect(page.locator('#games .card')).toHaveCount(105);
 await page.locator('#search').fill('homard');
 await expect(page.locator('#games .card').first()).toContainText('homard',{ignoreCase:true});
 await page.locator('#games .favorite').first().click();
 await page.locator('#search').fill('');
 await page.locator('#favoritesOnly').check();
 await expect(page.locator('#games .card')).toHaveCount(1);
 await expect(page.locator('#games .card')).toContainText(['★ Retirer des favoris']);
 expect(page.__errors).toEqual([]);
});
test('générateur, édition, historique et mode animateur',async ({page})=>{
 await page.locator('#duration').selectOption('55');
 await page.getByRole('button',{name:'Générer ma séance'}).click();
 await expect(page.locator('#plan>.card')).toHaveCount(5);
 await expect(page.locator('#planSummary')).toContainText('55 minutes');
 const before=await page.locator('#plan>.card h3').allTextContents();
 expect(new Set(before).size).toBe(5);
 await page.locator('#plan .card').first().getByRole('button',{name:'+ 1 min'}).click();
 await expect(page.locator('#planSummary')).toContainText('56 minutes');
 await page.locator('#plan .card').first().getByRole('button',{name:'− 1 min'}).click();
 await expect(page.locator('#planSummary')).toContainText('55 minutes');
 await page.locator('#plan .card').first().getByRole('button',{name:/Descendre exercice/}).click();
 const moved=await page.locator('#plan>.card h3').allTextContents();
 expect(moved[1]).toBe(before[0]);
 await page.locator('#plan .card').first().getByRole('button',{name:'🔄 Remplacer'}).click();
 await page.getByRole('button',{name:'Enregistrer'}).click();
 await page.getByRole('button',{name:'Historique'}).click();
 await expect(page.locator('#historyResult .card')).toHaveCount(1);
 await page.getByRole('button',{name:'Réutiliser'}).click();
 await page.getByRole('button',{name:/Animateur/}).click();
 await expect(page.locator('#liveProgress')).toContainText('Exercice 1 / 5');
 const first=await page.locator('#liveTitle').textContent();
 await page.getByRole('button',{name:/Suivant/}).click();
 await expect(page.locator('#liveProgress')).toContainText('Exercice 2 / 5');
 await page.getByRole('button',{name:/Précédent/}).click();
 expect(await page.locator('#liveTitle').textContent()).toBe(first);
 await page.getByRole('button',{name:'+ 1 min'}).click();
 await page.getByRole('button',{name:/Démarrer/}).click();
 await expect(page.locator('#liveStart')).toContainText('Pause');
 await page.getByRole('button',{name:/Pause/}).click();
 await expect(page.locator('#liveStart')).toContainText('Reprendre');
 expect(page.__errors).toEqual([]);
});
test('glissement tactile et absence de débordement',async ({page})=>{
 await page.getByRole('button',{name:'Générer ma séance'}).click();
 await page.getByRole('button',{name:/Animateur/}).click();
 const area=page.locator('#liveClock');const box=await area.boundingBox();
 await page.touchscreen.tap(box.x+box.width/2,box.y+box.height/2);
 await page.evaluate(()=>{const e=document.querySelector('#liveClock'),r=e.getBoundingClientRect();e.dispatchEvent(new TouchEvent('touchstart',{bubbles:true,touches:[new Touch({identifier:1,target:e,clientX:r.right-10,clientY:r.top+20})]}));e.dispatchEvent(new TouchEvent('touchend',{bubbles:true,changedTouches:[new Touch({identifier:1,target:e,clientX:r.left+10,clientY:r.top+20})]}))});
 await expect(page.locator('#liveProgress')).toContainText('Exercice 2 / 5');
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2);
 expect(overflow).toBe(false);
 expect(page.__errors).toEqual([]);
});
